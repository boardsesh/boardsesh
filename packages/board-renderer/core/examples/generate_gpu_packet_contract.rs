//! Deterministic native constants; no duplicated descriptor/uniform offsets.
use board_renderer_core::aura::gpu_packet::{contract_manifest, contract_sha256};
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let directory = PathBuf::from(std::env::args().nth(1).ok_or("Expected output directory")?);
    std::fs::create_dir_all(&directory)?;
    let manifest = contract_manifest();
    std::fs::write(
        directory.join("aura-gpu-packet-v1.json"),
        format!("{}\n", serde_json::to_string_pretty(&manifest)?),
    )?;
    let mut swift = String::from(
        "// Generated by generate_gpu_packet_contract. Do not edit.\nimport Foundation\nenum ClimbOverlayPacketLayout {\n",
    );
    let mut kotlin = String::from(
        "// Generated by generate_gpu_packet_contract. Do not edit.\npackage com.boardsesh.climboverlaygpu\ninternal object OverlayPacketLayout {\n",
    );
    let mut header = String::from(
        "/* Generated by generate_gpu_packet_contract. Do not edit. */\n#ifndef AURA_GPU_PACKET_LAYOUT_H\n#define AURA_GPU_PACKET_LAYOUT_H\n",
    );
    for (key, value) in manifest.as_object().ok_or("Invalid contract")? {
        if let Some(number) = value.as_i64() {
            swift.push_str(&format!("  static let {key}: Int = {number}\n"));
            kotlin.push_str(&format!("  const val {}: Int = {number}\n", snake(key)));
            header.push_str(&format!("#define AURA_GPU_{} {number}u\n", snake(key)));
        } else if let Some(members) = value.as_object() {
            for (member, number) in members {
                let number = number.as_i64().ok_or("Invalid offset")?;
                swift.push_str(&format!(
                    "  static let {key}{}: Int = {number}\n",
                    upper_first(member)
                ));
                kotlin.push_str(&format!(
                    "  const val {}_{}: Int = {number}\n",
                    snake(key),
                    snake(member)
                ));
                header.push_str(&format!(
                    "#define AURA_GPU_{}_{} ({number})\n",
                    snake(key),
                    snake(member)
                ));
            }
        }
    }
    swift.push_str(concat!(
        "  static let editDurationSeconds: Double = Double(editDurationMs) / 1000.0\n",
        "  static let editPeakTimeSeconds: Double = Double(editPeakTimeMs) / 1000.0\n",
        "  static let editPeakReach = Float(bitPattern: UInt32(editPeakReachBits))\n",
        "  static let revealBand = Float(bitPattern: UInt32(revealBandBits))\n",
    ));
    kotlin.push_str(concat!(
        "  const val EDIT_DURATION_NS: Long = EDIT_DURATION_MS * 1_000_000L\n",
        "  const val EDIT_PEAK_NS: Long = EDIT_PEAK_TIME_MS * 1_000_000L\n",
        "  val EDIT_PEAK_REACH: Float = Float.fromBits(EDIT_PEAK_REACH_BITS)\n",
        "  val REVEAL_BAND: Float = Float.fromBits(REVEAL_BAND_BITS)\n",
    ));
    swift.push_str(&format!(
        "  static let contractSha256 = \"{}\"\n}}\n",
        contract_sha256()
    ));
    kotlin.push_str(&format!(
        "  const val CONTRACT_SHA256 = \"{}\"\n}}\n",
        contract_sha256()
    ));
    header.push_str(&format!(
        "#define AURA_GPU_CONTRACT_SHA256 \"{}\"\n#endif\n",
        contract_sha256()
    ));
    std::fs::write(directory.join("ClimbOverlayPacketLayout.swift"), swift)?;
    std::fs::write(directory.join("OverlayPacketLayout.kt"), kotlin)?;
    std::fs::write(directory.join("aura_gpu_packet_layout.h"), header)?;
    println!(
        "{}",
        serde_json::json!({"contractSha256":contract_sha256(),"directory":directory})
    );
    Ok(())
}
fn upper_first(text: &str) -> String {
    let mut chars = text.chars();
    chars
        .next()
        .map(|first| first.to_uppercase().chain(chars).collect())
        .unwrap_or_default()
}
fn snake(text: &str) -> String {
    let mut result = String::new();
    for character in text.chars() {
        if character.is_uppercase() {
            result.push('_');
        }
        result.push(character.to_ascii_uppercase());
    }
    result
}
