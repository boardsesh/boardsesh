import { BOARD_BACKGROUND_ASSETS } from './board-backgrounds-manifest';

// Which bundled file a piece of board art resolves to: the variant and
// colour-scheme rules on top of the generated manifest. Kept apart from
// background-image-cache.ts, which eagerly imports `expo-asset`, so a component
// that only needs a module id (the MoonBoard grid labels, drawn inside every
// `BoardImageNative`) does not pull that native module into every board test.

/**
 * Which bundled variant of a board background to resolve. `full` is the
 * native-resolution webp; `thumb` is the 416px-wide webp generated by
 * packages/web/scripts/generate-thumbnails.sh. Small/decorative surfaces
 * (list thumbnails, blurred playlist backdrops) request `thumb` so
 * expo-image never has to resample a ~1080px source on the main thread.
 */
export type BackgroundVariant = 'full' | 'thumb';

/**
 * Which colour scheme the art is being rendered into. Only `dark` can change
 * which file resolves; `light` (the default) always resolves exactly what it
 * resolved before dark variants existed.
 */
export type BackgroundColorScheme = 'light' | 'dark';

/**
 * Suffix marking a dark-mode sibling, e.g.
 * `moonboard/moonboard2016/holdsetb.webp` -> `moonboard/moonboard2016/holdsetb.dark.webp`.
 * Written by scripts/generate-dark-board-art.ts; keep the two in sync.
 */
const DARK_VARIANT_SUFFIX = '.dark.webp';

/**
 * Map a full-resolution background manifest key produced by getBoardRenderData
 * to the requested bundled variant. The manifest stores .webp variants —
 * full-quality webp is what we bundle into the IPA/APK for every board
 * background, plus a `thumbs/` sibling for most boards.
 *
 * Manifest keys are paths relative to the bundled board-art manifest, e.g.
 * `kilter/product_sizes_layouts_sets/36-1.webp`. The thumb variant inserts a
 * `thumbs/` segment before the filename, e.g.
 * `kilter/product_sizes_layouts_sets/thumbs/36-1.webp`.
 */
function manifestKeyForVariant(backgroundImageKey: string, variant: BackgroundVariant = 'full'): string {
  if (variant === 'full') return backgroundImageKey;
  const lastSlash = backgroundImageKey.lastIndexOf('/');
  if (lastSlash < 0) return `thumbs/${backgroundImageKey}`;
  return `${backgroundImageKey.slice(0, lastSlash)}/thumbs/${backgroundImageKey.slice(lastSlash + 1)}`;
}

/**
 * Resolve the best bundled manifest key for a background key + variant + scheme.
 * When `thumb` is requested but no thumb was bundled (e.g. a board that
 * ships only a full-res webp), fall back to the full-res key — never to
 * the backend.
 *
 * In dark mode, prefer a `.dark.webp` sibling when one is bundled. Only the
 * handful of MoonBoard layers that are drawn in near-black have one (see
 * scripts/generate-dark-board-art.ts for which, and why): MoonBoard's art is
 * drawn for a white wall, so its grid frame, its A-K / 1-18 labels and its
 * black plastic hold sheets measure ~1.1:1 against the dark play field and
 * disappear (issue #3885). Every other board draws mid-tone art that already
 * reads, has no sibling, and so falls through here unchanged — as does every
 * layer in light mode. That fallback is what keeps this from being a per-board
 * special case. The MoonBoard grid labels resolve their dark copy by this same
 * rule, through `bundledBoardArtSource`.
 */
export function resolveManifestKey(
  backgroundImageKey: string,
  variant: BackgroundVariant,
  colorScheme: BackgroundColorScheme,
): string {
  let manifestKey = backgroundImageKey;
  if (variant === 'thumb') {
    const thumbKey = manifestKeyForVariant(backgroundImageKey, 'thumb');
    if (BOARD_BACKGROUND_ASSETS[thumbKey] !== undefined) manifestKey = thumbKey;
  }
  if (colorScheme === 'dark') {
    const darkKey = `${manifestKey.replace(/\.webp$/, '')}${DARK_VARIANT_SUFFIX}`;
    if (BOARD_BACKGROUND_ASSETS[darkKey] !== undefined) return darkKey;
  }
  return manifestKey;
}

/**
 * The bundled module id for one piece of board art, in the colour scheme it is
 * drawn into: the `.dark.webp` sibling in dark mode when one exists. `null` when
 * nothing is bundled under the key.
 *
 * For art an `<Image>` draws straight from the bundle rather than from a resolved
 * file path: the MoonBoard grid labels, which sit above the holds overlay instead
 * of in the background stack (issue #6234). Always the `full` variant, because
 * the labels only draw on full-size boards.
 */
export function bundledBoardArtSource(manifestKey: string, colorScheme: BackgroundColorScheme): number | null {
  return BOARD_BACKGROUND_ASSETS[resolveManifestKey(manifestKey, 'full', colorScheme)] ?? null;
}
