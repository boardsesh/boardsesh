/// <reference types="node" />

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const { values } = parseArgs({
  options: {
    compiler: { type: 'string' },
    source: {
      type: 'string',
      default:
        'packages/mobile/modules/climb-overlay-gpu/android/src/main/java/com/boardsesh/climboverlaygpu/OverlayShader.kt',
    },
  },
});
if (!values.compiler) throw new Error('Pass --compiler with the Android NDK glslc path.');

const kotlinSource = readFileSync(resolve(values.source), 'utf8');
const layoutSource = readFileSync(join(dirname(resolve(values.source)), 'OverlayPacketLayout.kt'), 'utf8');
if (!layoutSource.startsWith('// Generated by generate_gpu_packet_contract. Do not edit.')) {
  throw new Error('Expected generated Rust packet constants.');
}
const layoutConstants = new Map(
  [...layoutSource.matchAll(/const val ([A-Z_]+): Int = (\d+)/g)].map((match) => [match[1], match[2]]),
);
// The base program (vertex + fragment) and the swap look's program (vertex + lookFragment).
const shaderStages: Record<string, string> = {
  vertex: 'overlay.vert',
  fragment: 'overlay.frag',
  lookFragment: 'overlay-look.frag',
};
const shaderMatches = [
  ...kotlinSource.matchAll(/val\s+(vertex|fragment|lookFragment)\s*=\s*"""([\s\S]*?)"""\s*\.trimIndent\(\)/g),
];
if (shaderMatches.length !== 3 || new Set(shaderMatches.map((match) => match[1])).size !== 3) {
  throw new Error('Expected exactly one literal vertex, fragment and lookFragment shader with trimIndent().');
}
// Adreno 840 drops a Hold returned straight from a storage-buffer element (#7749).
// Copy it into a local first; glslc accepts both forms, so it won't catch this.
// Matches any return that ends on a whole element, in any parentheses or ternary,
// but not a field read such as `return lower[i].crop`. It may also flag a call
// that takes an element; the shader has none.
const directStructReturn = /\breturn\b[^;]*\b(lower|upper)\s*\[(?:[^[\]]|\[[^\]]*\])*\][\s)]*;/;
for (const [, stage, literal] of shaderMatches) {
  const match = directStructReturn.exec(literal);
  if (match) throw new Error(`${stage}: returns ${match[1]}[...] directly; copy the Hold into a local first (#7749).`);
}

const outputDirectory = mkdtempSync(join(tmpdir(), 'boardsesh-gpu-shaders-'));
try {
  for (const [, stage, literal] of shaderMatches) {
    const expandedLiteral = literal.replace(/\$\{OverlayPacketLayout\.([A-Z_]+)\}/g, (_expression, name: string) => {
      const constant = layoutConstants.get(name);
      if (constant === undefined) throw new Error(`${stage}: unknown generated constant ${name}.`);
      return constant;
    });
    if (expandedLiteral.includes('$')) throw new Error(`${stage}: unsupported shader interpolation.`);
    // Match Kotlin trimIndent: drop blank boundary lines, then remove the
    // smallest indentation from nonblank lines. Validate the shipped strings,
    // not a second shader fixture that could drift from the native renderer.
    const lines = expandedLiteral.split(/\r?\n/);
    if (lines[0].trim() === '') lines.shift();
    if (lines.at(-1)?.trim() === '') lines.pop();
    const indentation = Math.min(...lines.filter((line) => line.trim()).map((line) => line.search(/\S/)));
    const shader = lines.map((line) => (line.trim() ? line.slice(indentation) : '')).join('\n');
    if (!shader.startsWith('#version 310 es\n')) throw new Error(`${stage}: expected GLSL ES 3.1.`);
    const shaderPath = join(outputDirectory, shaderStages[stage]);
    writeFileSync(shaderPath, shader);
    const result = spawnSync(
      values.compiler,
      [
        '-std=310es',
        '--target-env=opengl',
        '-fauto-map-locations',
        '-fauto-bind-uniforms',
        shaderPath,
        '-o',
        `${shaderPath}.spv`,
      ],
      { encoding: 'utf8', timeout: 30_000 },
    );
    if (result.error || result.status !== 0) {
      throw new Error(`${stage} shader failed: ${result.error?.message ?? result.stderr ?? result.stdout}`);
    }
    console.log(`[android-gpu-shaders] ${stage}: GLSL ES 3.1 compilation passed`);
  }
} finally {
  rmSync(outputDirectory, { recursive: true });
}
