import { execFileSync } from 'node:child_process';
import { chmodSync, mkdirSync, mkdtempSync, rmSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { checkChangelogOwnership, type ChangelogOwnershipContext } from './check-changelog-ownership';

const GENERATED = ['CHANGELOG.md', 'packages/mobile/src/data/changelog.generated.json'];
const directories: string[] = [];
function fixture() {
  const cwd = mkdtempSync(join(tmpdir(), 'changelog-guard-'));
  directories.push(cwd);
  const git = (...args: string[]) =>
    execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  const write = (path: string, contents: string) => {
    mkdirSync(dirname(join(cwd, path)), { recursive: true });
    writeFileSync(join(cwd, path), contents);
  };
  const commit = () => {
    git('add', '.');
    git('commit', '-m', 'fixture');
    return git('rev-parse', 'HEAD');
  };
  git('init', '--initial-branch=main');
  git('config', 'user.name', 'Ownership test');
  git('config', 'user.email', 'ownership@example.com');
  for (const path of GENERATED) write(path, 'Generated by OTA\n');
  const baseSha = commit();
  write('feature.txt', 'Ordinary feature\n');
  const context: ChangelogOwnershipContext = { baseBranch: 'main', baseSha, headSha: commit() };
  return { cwd, git, write, commit, context };
}
afterEach(() => {
  for (const directory of directories.splice(0)) rmSync(directory, { recursive: true, force: true });
});

describe('generated changelog ownership', () => {
  it('allows an ordinary PR that leaves generated files untouched', () => {
    const { cwd, context } = fixture();
    expect(checkChangelogOwnership(context, cwd)).toBe(context.headSha);
  });
  it.each(['main', 'release/next', 'feature/other'])(
    'rejects generated edits on %s without an import waiver',
    (baseBranch) => {
      const { cwd, context, write, commit } = fixture();
      write(GENERATED[0], 'Manual edit\n');
      expect(() => checkChangelogOwnership({ ...context, baseBranch, headSha: commit() }, cwd)).toThrow('owned by');
    },
  );
  it.each(GENERATED)('rejects deletion of %s', (path) => {
    const { cwd, context, git, commit } = fixture();
    git('rm', '--', path);
    expect(() => checkChangelogOwnership({ ...context, headSha: commit() }, cwd)).toThrow('owned by');
  });
  it.each(['symlink', 'executable'])('rejects %s replacement even if contents are unchanged', (mode) => {
    const { cwd, context, commit } = fixture();
    const path = join(cwd, GENERATED[0]);
    if (mode === 'symlink') {
      unlinkSync(path);
      symlinkSync('feature.txt', path);
    } else chmodSync(path, 0o755);
    expect(() => checkChangelogOwnership({ ...context, headSha: commit() }, cwd)).toThrow('owned by');
  });
  it('rejects missing, abbreviated and nonexistent commit identities', () => {
    const { cwd, context } = fixture();
    for (const headSha of [undefined, 'main', 'a'.repeat(12), 'a'.repeat(40)]) {
      expect(() => checkChangelogOwnership({ ...context, headSha }, cwd)).toThrow();
    }
  });
});
