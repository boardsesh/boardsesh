import { execFileSync } from 'node:child_process';
import { chmodSync, mkdirSync, mkdtempSync, rmSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { checkChangelogOwnership, type ChangelogOwnershipContext } from './check-changelog-ownership';

const GENERATED_CHANGELOGS = ['CHANGELOG.md', 'packages/mobile/src/data/changelog.generated.json'];
const fixtures: string[] = [];

function fixture() {
  const cwd = mkdtempSync(join(tmpdir(), 'changelog-ownership-'));
  fixtures.push(cwd);
  const git = (...args: string[]) =>
    execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  const write = (path: string, content: string) => {
    mkdirSync(dirname(join(cwd, path)), { recursive: true });
    writeFileSync(join(cwd, path), content);
  };
  const commit = (message: string) => {
    git('add', '.');
    git('commit', '-m', message);
    return git('rev-parse', 'HEAD');
  };
  git('init', '--initial-branch=main');
  git('config', 'user.name', 'Changelog ownership test');
  git('config', 'user.email', 'changelog-test@example.com');
  for (const path of GENERATED_CHANGELOGS) write(path, 'Already shipped\n');
  const rootSha = commit('Initial history');
  git('checkout', '-b', 'release/next');
  write('native.txt', 'Native train changes\n');
  const baseSha = commit('Native train');
  git('checkout', 'main');
  for (const path of GENERATED_CHANGELOGS) write(path, 'Generated by main OTA\n');
  const mainSha = commit('OTA generated changelog');
  git('update-ref', 'refs/remotes/origin/main', mainSha);
  git('checkout', '-b', 'ordinary-review-branch', baseSha);
  git('merge', '--no-ff', 'main', '-m', 'Import main');
  const context: ChangelogOwnershipContext = {
    baseBranch: 'release/next',
    baseSha,
    headSha: git('rev-parse', 'HEAD'),
  };
  return { cwd, git, write, commit, context, rootSha, mainSha };
}

afterEach(() => {
  for (const cwd of fixtures.splice(0)) rmSync(cwd, { recursive: true, force: true });
});

describe('generated changelog ownership', () => {
  it('allows exact bot-generated files carried from main into the native train', () => {
    const { cwd, context, mainSha } = fixture();
    expect(checkChangelogOwnership(context, cwd)).toBe(mainSha);
  });

  it.each(GENERATED_CHANGELOGS)('rejects a hand edit to %s even after importing main', (path) => {
    const { cwd, context, write, commit } = fixture();
    write(path, 'Manual changelog edit\n');
    context.headSha = commit('Hand edit');
    expect(() => checkChangelogOwnership(context, cwd)).toThrow('differs from');
  });

  it.each(GENERATED_CHANGELOGS)('rejects deleting %s', (path) => {
    const { cwd, context, git, commit } = fixture();
    git('rm', '--', path);
    context.headSha = commit('Delete generated file');
    expect(() => checkChangelogOwnership(context, cwd)).toThrow('differs from');
  });

  it.each(GENERATED_CHANGELOGS.flatMap((path) => ['symlink', 'executable'].map((mode) => ({ path, mode }))))(
    'rejects $mode replacement of $path even with an identical blob',
    ({ path, mode }) => {
      const { cwd, context, commit, git, mainSha } = fixture();
      if (mode === 'symlink') {
        unlinkSync(join(cwd, path));
        symlinkSync('Generated by main OTA\n', join(cwd, path));
      } else {
        chmodSync(join(cwd, path), 0o755);
      }
      context.headSha = commit('Change generated file mode');
      expect(git('rev-parse', `${context.headSha}:${path}`)).toBe(git('rev-parse', `${mainSha}:${path}`));
      expect(() => checkChangelogOwnership(context, cwd)).toThrow('differs from');
    },
  );

  it('rejects normal PR targets', () => {
    const { cwd, context } = fixture();
    expect(() => checkChangelogOwnership({ ...context, baseBranch: 'main' }, cwd)).toThrow('release/next');
  });

  it('rejects a regular train PR that copies main files without importing its history', () => {
    const { cwd, context, git, write, commit } = fixture();
    git('checkout', '--detach', context.baseSha!);
    for (const path of GENERATED_CHANGELOGS) write(path, 'Generated by main OTA\n');
    context.headSha = commit('Copy generated files');
    expect(() => checkChangelogOwnership(context, cwd)).toThrow('no new trusted main history');
  });

  it('rejects already-imported main history', () => {
    const { cwd, context } = fixture();
    context.baseSha = context.headSha;
    expect(() => checkChangelogOwnership(context, cwd)).toThrow('no new trusted main history');
  });

  it('uses the imported main snapshot when main advances before CI runs', () => {
    const { cwd, context, git, write, commit, mainSha } = fixture();
    git('checkout', 'main');
    for (const path of GENERATED_CHANGELOGS) write(path, 'A later OTA on main\n');
    git('update-ref', 'refs/remotes/origin/main', commit('Next OTA'));
    expect(checkChangelogOwnership(context, cwd)).toBe(mainSha);
  });

  it.each([
    { baseBranch: undefined },
    { baseSha: undefined },
    { headSha: undefined },
    { headSha: 'HEAD' },
    { baseSha: '--all' },
    { headSha: 'f'.repeat(40) },
  ])('rejects incomplete or invalid context %j', (overrides) => {
    const { cwd, context } = fixture();
    expect(() => checkChangelogOwnership({ ...context, ...overrides }, cwd)).toThrow();
  });

  it('rejects missing trusted main', () => {
    const { cwd, context, git } = fixture();
    git('update-ref', '-d', 'refs/remotes/origin/main');
    expect(() => checkChangelogOwnership(context, cwd)).toThrow();
  });

  it('rejects shallow history even when all three input commits resolve', () => {
    const { cwd, context, mainSha } = fixture();
    const shallowDirectory = mkdtempSync(join(tmpdir(), 'changelog-ownership-shallow-'));
    fixtures.push(shallowDirectory);
    execFileSync('git', ['clone', '--depth=2', '--branch=ordinary-review-branch', `file://${cwd}`, shallowDirectory], {
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    execFileSync('git', ['update-ref', 'refs/remotes/origin/main', mainSha], { cwd: shallowDirectory });
    expect(() => checkChangelogOwnership(context, shallowDirectory)).toThrow('Complete history');
  });

  it('rejects a head that does not retain the train history', () => {
    const { cwd, context, mainSha } = fixture();
    expect(() => checkChangelogOwnership({ ...context, headSha: mainSha }, cwd)).toThrow('retain');
  });

  it('rejects an unrelated trusted main history', () => {
    const { cwd, context, git } = fixture();
    const unrelated = git('commit-tree', 'HEAD^{tree}', '-m', 'Unrelated root');
    git('update-ref', 'refs/remotes/origin/main', unrelated);
    expect(() => checkChangelogOwnership(context, cwd)).toThrow();
  });

  it('rejects merging unrelated main history into the train', () => {
    const { cwd, context, git } = fixture();
    const unrelated = git('commit-tree', 'HEAD^{tree}', '-m', 'Unrelated root');
    git('update-ref', 'refs/remotes/origin/main', unrelated);
    context.headSha = git(
      'commit-tree',
      'HEAD^{tree}',
      '-p',
      context.baseSha!,
      '-p',
      unrelated,
      '-m',
      'Unrelated import',
    );
    expect(() => checkChangelogOwnership(context, cwd)).toThrow();
  });

  it('rejects ambiguous main ancestry in a criss-cross merge', () => {
    const { cwd, context, git, rootSha } = fixture();
    const first = git('commit-tree', 'HEAD^{tree}', '-p', rootSha, '-m', 'First side');
    const second = git('commit-tree', 'HEAD^{tree}', '-p', rootSha, '-m', 'Second side');
    const headSha = git('commit-tree', 'HEAD^{tree}', '-p', first, '-p', second, '-m', 'First merge');
    const mainSha = git('commit-tree', 'HEAD^{tree}', '-p', second, '-p', first, '-m', 'Second merge');
    git('update-ref', 'refs/remotes/origin/main', mainSha);
    expect(() => checkChangelogOwnership({ ...context, baseSha: rootSha, headSha }, cwd)).toThrow('unambiguous');
  });
});
