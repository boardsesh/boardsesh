#!/usr/bin/env python3
"""Generate the app's Material Design icon outlines without runtime font loading.

From the repo root: uv run --with fonttools==4.62.1 scripts/generate-mobile-icon-paths.py
Requires the installed mobile workspace dependencies. Output is deterministic.
"""

import json
from pathlib import Path
import re
import subprocess

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
MOBILE = ROOT / "packages/mobile"
VECTOR_ICONS = MOBILE / "node_modules/@expo/vector-icons"
VENDOR = VECTOR_ICONS / "build/vendor/react-native-vector-icons"
OUTPUT = MOBILE / "src/components/material-icon-paths.ts"
PINNED_VECTOR_ICONS_VERSION = "15.1.1"
STRING_LITERAL = re.compile(r"(['\"])([a-z][a-z0-9-]*)\1")


def main() -> None:
    installed_version = json.loads((VECTOR_ICONS / "package.json").read_text())["version"]
    if installed_version != PINNED_VECTOR_ICONS_VERSION:
        raise SystemExit(
            f"Expected @expo/vector-icons {PINNED_VECTOR_ICONS_VERSION}, got {installed_version}. "
            "Review the new font and update the generator pin before regenerating."
        )

    glyph_map = json.loads((VENDOR / "glyphmaps/MaterialCommunityIcons.json").read_text())
    source_roots = [
        MOBILE / "src/components",
        MOBILE / "src/providers",
        MOBILE / "node_modules/react-native-paper/src",
    ]
    names: set[str] = set()
    for source_root in source_roots:
        if not source_root.is_dir():
            raise SystemExit(f"Missing source directory: {source_root}")
        for source_path in sorted(source_root.rglob("*")):
            if source_path.suffix not in {".ts", ".tsx"}:
                continue
            if source_path == OUTPUT:
                continue
            names.update(
                match.group(2)
                for match in STRING_LITERAL.finditer(source_path.read_text())
                if match.group(2) in glyph_map
            )

    font = TTFont(VENDOR / "Fonts/MaterialCommunityIcons.ttf")
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    units_per_em = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    outlines: dict[str, str] = {}
    for name in sorted(names):
        # The font intentionally omits MDI's "blank" sentinel. Paper uses it
        # to reserve icon space without painting a glyph.
        if name == "blank":
            outlines[name] = ""
            continue
        glyph_name = cmap[glyph_map[name]]
        pen = SVGPathPen(glyph_set)
        # Font coordinates rise from the baseline. SVG coordinates descend from
        # the top of the em square: MDI's 448 ascent + 64 descent = 512 units.
        glyph_set[glyph_name].draw(TransformPen(pen, (1, 0, 0, -1, 0, ascent)))
        outlines[name] = pen.getCommands()
        if not outlines[name]:
            raise SystemExit(f"Icon {name!r} has an empty outline")

    header = """// Generated by scripts/generate-mobile-icon-paths.py. Do not edit by hand.
// Regenerate: uv run --with fonttools==4.62.1 scripts/generate-mobile-icon-paths.py
// Outlines: @expo/vector-icons 15.1.1 MaterialCommunityIcons.ttf (MDI 7.4.47).
// @expo/vector-icons / react-native-vector-icons: MIT license.
// Material Design Icons by Pictogrammers: Apache-2.0; https://pictogrammers.com/docs/general/license/
// Only icons referenced by the app and react-native-paper are included.
"""
    lines = [header, f"export const materialIconViewBox = '0 0 {units_per_em} {units_per_em}';\n"]
    lines.append("export const materialIconPaths = {\n")
    lines.extend(f"  {json.dumps(name)}: {json.dumps(outline)},\n" for name, outline in outlines.items())
    lines.append("} as const;\n\nexport type MaterialIconName = keyof typeof materialIconPaths;\n")
    OUTPUT.write_text("".join(lines))
    subprocess.run(["vp", "fmt", str(OUTPUT)], cwd=ROOT, check=True)
    print(f"Generated {len(outlines)} icons, {OUTPUT.stat().st_size} bytes: {OUTPUT.relative_to(ROOT)}")
    print(f"Font transform: x'=x, y'={ascent}-y; viewBox 0 0 {units_per_em} {units_per_em}")


if __name__ == "__main__":
    main()
