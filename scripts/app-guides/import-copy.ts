#!/usr/bin/env tsx
/**
 * Import writer copy for the board-app comparison pages (/apps, /apps/<board>,
 * /compare/spray-wall-apps).
 *
 *   vp run app-guides:import -- <copy-dir> [--allow-pending] [--draft] [--check] [--only kilter,hub] [--date YYYY-MM-DD]
 *
 * Reads `<copy-dir>/<page>.json` for every page id it finds (hub, the board
 * guides in APP_GUIDE_SLUGS, spray-wall-apps) and writes:
 *
 * - `pages.<page>` in `appGuides.json` for every locale folder. Only English is
 *   published; the other catalogs carry the same English text so key parity
 *   holds. `common` is hand-edited in en-US and copied across on every run.
 * - `packages/web/app/lib/seo/app-guide-registry.generated.ts`: the structure.
 *
 * Pages without a copy file keep what the catalog and registry already hold.
 * A page's "Updated" date moves only when its imported text or structure
 * changed, so a re-run with the same copy is a no-op.
 *
 * Exit code 1 on any error (length caps, counts, verdicts, unknown source ids,
 * `[PENDING-…]` placeholders without --allow-pending). `--check` validates only.
 * `--draft` turns every error into a warning for a dev-server preview of an
 * unedited draft; the import that gets committed runs without it.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  APP_GUIDE_PAGE_IDS,
  type AppGuidePageId,
  type AppGuideRegistry,
  type GuideQuote,
} from '../../packages/web/app/lib/seo/app-guide-model';
import { importPage, importQuotes, type CatalogPage, type ImportIssue } from './import-copy-lib';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const LOCALES_DIR = join(repoRoot, 'packages/shared/i18n/locales');
const SOURCE_LOCALE = 'en-US';
const REGISTRY_FILE = join(repoRoot, 'packages/web/app/lib/seo/app-guide-registry.generated.ts');

type Catalog = { common: CatalogPage; pages: Record<string, CatalogPage> };

function parseArgs(argv: string[]) {
  const options = {
    allowPending: false,
    draft: false,
    check: false,
    only: undefined as string[] | undefined,
    date: undefined as string | undefined,
  };
  const positional: string[] = [];
  for (let index = 0; index < argv.length; index++) {
    const arg = argv[index];
    if (arg === '--allow-pending') options.allowPending = true;
    else if (arg === '--draft') options.draft = true;
    else if (arg === '--check') options.check = true;
    else if (arg === '--only' || arg === '--date') {
      const value = argv[++index];
      if (!value || value.startsWith('--')) throw new Error(`${arg} needs a value`);
      if (arg === '--only') options.only = value.split(',');
      else options.date = value;
    } else if (arg === '--') continue;
    else if (arg.startsWith('--')) throw new Error(`Unknown flag ${arg}`);
    else positional.push(arg);
  }
  if (positional.length !== 1) {
    throw new Error('Usage: import-copy.ts <copy-dir> [--allow-pending] [--check] [--only a,b] [--date YYYY-MM-DD]');
  }
  if (options.date && !/^\d{4}-\d{2}-\d{2}$/.test(options.date)) throw new Error('--date must be YYYY-MM-DD');
  return { copyDir: resolve(positional[0]), ...options };
}

async function loadRegistry(): Promise<{ registry: Partial<AppGuideRegistry>; quotes: readonly GuideQuote[] }> {
  if (!existsSync(REGISTRY_FILE)) return { registry: {}, quotes: [] };
  const module = (await import(pathToFileURL(REGISTRY_FILE).href)) as {
    APP_GUIDE_REGISTRY: AppGuideRegistry;
    APP_GUIDE_QUOTES?: readonly GuideQuote[];
  };
  return { registry: module.APP_GUIDE_REGISTRY, quotes: module.APP_GUIDE_QUOTES ?? [] };
}

function formatIssue(issue: ImportIssue) {
  return `  ${issue.severity === 'error' ? 'error' : 'warn '}  ${issue.page}: ${issue.path} ${issue.message}`;
}

/** Compare everything but the date, so formatting and key order never bump a page. */
function fingerprint(catalog: CatalogPage | undefined, registry: object | undefined): string {
  if (!catalog || !registry) return '';
  const { updatedAt: _updatedAt, ...structure } = registry as { updatedAt?: string };
  return JSON.stringify([catalog, structure]);
}

function writeRegistry(registry: AppGuideRegistry, quotes: readonly GuideQuote[]) {
  const ordered = Object.fromEntries(APP_GUIDE_PAGE_IDS.map((id) => [id, registry[id]]));
  const source = [
    '// Generated by scripts/app-guides/import-copy.ts from the writer copy files. Do not edit by hand:',
    '// change the copy and re-run `vp run app-guides:import -- <copy-dir>`. Text lives in appGuides.json.',
    "import type { AppGuideRegistry, GuideQuote } from './app-guide-model';",
    '',
    `export const APP_GUIDE_REGISTRY = ${JSON.stringify(ordered, null, 2)} as const satisfies AppGuideRegistry;`,
    '',
    '// Verbatim store reviews from quotes.json: user-generated, so never in the translated catalog.',
    `export const APP_GUIDE_QUOTES: readonly GuideQuote[] = ${JSON.stringify(quotes, null, 2)};`,
    '',
  ].join('\n');
  writeFileSync(REGISTRY_FILE, source);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const today = args.date ?? new Date().toISOString().slice(0, 10);
  const files = new Set(readdirSync(args.copyDir).filter((file) => file.endsWith('.json')));
  const pages = APP_GUIDE_PAGE_IDS.filter(
    (id) => files.has(`${id}.json`) && (!args.only || args.only.includes(id)),
  ) as AppGuidePageId[];
  if (pages.length === 0) throw new Error(`No page copy (${APP_GUIDE_PAGE_IDS.join(', ')}) in ${args.copyDir}`);

  const sourceCatalogPath = join(LOCALES_DIR, SOURCE_LOCALE, 'appGuides.json');
  const catalog = JSON.parse(readFileSync(sourceCatalogPath, 'utf8')) as Catalog;
  const loaded = await loadRegistry();
  const registry = loaded.registry as Record<string, unknown>;
  const issues: ImportIssue[] = [];
  const changed: string[] = [];
  let quotes = loaded.quotes;
  if (files.has('quotes.json')) {
    const result = importQuotes(
      JSON.parse(readFileSync(join(args.copyDir, 'quotes.json'), 'utf8')) as Record<string, unknown>,
    );
    issues.push(...result.issues);
    if (JSON.stringify(result.quotes) !== JSON.stringify(quotes)) changed.push('quotes');
    quotes = result.quotes;
  }

  for (const page of pages) {
    const json = JSON.parse(readFileSync(join(args.copyDir, `${page}.json`), 'utf8')) as Record<string, unknown>;
    const result = importPage(page, json, { allowPending: args.allowPending, draft: args.draft });
    issues.push(...result.issues);
    const previous = registry[page] as { updatedAt?: string } | undefined;
    const same = fingerprint(catalog.pages[page], previous) === fingerprint(result.catalog, result.registry);
    const updatedAt = same && previous?.updatedAt ? previous.updatedAt : today;
    if (!same) changed.push(page);
    catalog.pages[page] = result.catalog;
    registry[page] = { ...result.registry, updatedAt };
  }

  const missing = APP_GUIDE_PAGE_IDS.filter((id) => !catalog.pages[id] || !registry[id]);
  for (const id of missing) {
    issues.push({ page: id, path: '', message: 'has no imported copy yet; pass its <page>.json', severity: 'error' });
  }

  for (const issue of issues) console.log(formatIssue(issue));
  const errors = issues.filter((issue) => issue.severity === 'error');
  console.log(
    `\n${pages.length} page(s) read, ${errors.length} error(s), ${issues.length - errors.length} warning(s). Changed: ${changed.join(', ') || 'none'}.`,
  );
  if (errors.length > 0) process.exit(1);
  if (args.check) return;

  // Canonical page order, then every locale folder gets the English source.
  catalog.pages = Object.fromEntries(APP_GUIDE_PAGE_IDS.map((id) => [id, catalog.pages[id]]));
  const text = `${JSON.stringify(catalog, null, 2)}\n`;
  const written: string[] = [];
  for (const locale of readdirSync(LOCALES_DIR, { withFileTypes: true })) {
    const target = join(LOCALES_DIR, locale.name, 'appGuides.json');
    if (!locale.isDirectory() || !existsSync(target)) continue;
    writeFileSync(target, text);
    written.push(relative(repoRoot, target));
  }
  writeRegistry(registry as AppGuideRegistry, quotes);
  written.push(relative(repoRoot, REGISTRY_FILE));
  // Leave the files in the repo's formatting, so a re-run produces no diff.
  const format = spawnSync('vp', ['check', '--fix', ...written], { cwd: repoRoot, stdio: 'ignore' });
  if (format.status !== 0) {
    console.error('`vp check --fix` failed on the written files; run it by hand before committing.');
    process.exit(1);
  }
  console.log(`Wrote ${written.length} files.`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
